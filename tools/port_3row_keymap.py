#!/usr/bin/env python3
"""Make the 3-row keymaps (config/yoga3_split.keymap, config/yoga3_mono.keymap) from the 4-row ones.

The 3-row board is the 4-row board minus the number row, in the same key order, so each layer
just loses its first 12 bindings. Numbers and the symbols from the number row live on the NUM
layer already. Everything else (behaviors, macros, layers) is kept as is.
usage: python3 tools/port_3row_keymap.py
"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def fmt(toks):
    width = max(len(t) for t in toks)
    rows = [toks[i:i + 12] for i in range(0, 36, 12)]
    out = ['    ' + ' '.join(t.ljust(width) for t in r[:6]) + '    ' + ' '.join(t.ljust(width) for t in r[6:]) for r in rows]
    out.append(' ' * (4 + 3 * (width + 1)) + ' '.join(t.ljust(width) for t in toks[36:39]) + '    ' + ' '.join(t.ljust(width) for t in toks[39:]))
    return '\n'.join(l.rstrip() for l in out)

def drop_num_row(m):
    toks = [t.strip() for t in re.split(r'(?=&)', m.group(2)) if t.strip()]
    assert len(toks) == 54, len(toks)
    return m.group(1) + '\n' + fmt(toks[12:]) + '\n' + m.group(3)

for src, dst in (('yoga_split.keymap', 'yoga3_split.keymap'), ('yoga_mono.keymap', 'yoga3_mono.keymap')):
    s = open(os.path.join(ROOT, 'config', src)).read()
    assert 'key-positions' not in s, 'combos/positional hold-taps need remapping by hand'
    s, n = re.subn(r'(bindings = <)(\n.*?)(\n\s*>;)', drop_num_row, s, flags=re.S)
    s = '// 3-row version of ' + src + ', generated by tools/port_3row_keymap.py (number row removed)\n' + s
    open(os.path.join(ROOT, 'config', dst), 'w').write(s)
    print(dst, n, 'layers')
