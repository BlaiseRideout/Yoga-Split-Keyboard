#!/usr/bin/env python3
"""Generate the ergogen footprints for the thin build's on-board controller from KiCad footprints:
  mdbt50q.js      Raytac MDBT50Q-1MV2 nRF52840 module  (KiCad library RF_Module:Raytac_MDBT50Q)
  usbc_mid.js     16-pin mid-mount USB-C, LCSC C168688  (from joric/nrfmicro, public domain)
  sot23.js        SOT-23-5 / SOT-23-6                   (KiCad library)
  xtal_3215.js    32.768 kHz crystal, 3.2 x 1.5 mm      (KiCad library)
Every pad gets a net param named after its pad number (P1, P2 ... or A4, B5 ... for the USB-C);
unconnected pads default to no net. usage: python3 tools/gen_ctrl_footprints.py [kicad footprint dir]"""
import os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LIB = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/kicad/footprints'
OUT = os.path.join(ROOT, 'ergogen/footprints')
NRFMICRO_USB = os.path.join(ROOT, 'tools/vendor/USB-C_C168688.kicad_mod')

PAD = re.compile(r'\(pad "?([^"\s]+)"? (\w+) (\w+) \(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\) \(size ([-\d.]+) ([-\d.]+)\)'
                 r'(?: \(drill (oval )?([-\d.]+)(?: ([-\d.]+))?\))? \(layers ([^)]*)\)(.*)')

def pads(path):
    out = []
    for line in open(path):
        m = PAD.search(line)
        if not m: continue
        num, kind, shape, x, y, a, w, h, oval, d1, d2, layers, rest = m.groups()
        layers = layers.replace('"', '')
        rr = re.search(r'roundrect_rratio ([\d.]+)', rest)
        out.append(dict(num=num, kind=kind, shape=shape, x=float(x), y=float(y), a=float(a or 0), w=float(w), h=float(h),
                        drill=(f'(drill oval {d1} {d2}) ' if oval else f'(drill {d1}) ') if d1 else '',
                        layers=layers, rr=f'(roundrect_rratio {rr.group(1)}) ' if rr else ''))
    return out

def pad_js(p, prefix='P'):
    name = p['num']
    param = prefix + name if name[0].isdigit() else name
    return (f"    (pad {name} {p['kind']} {p['shape']} (at {p['x']:g} {p['y']:g} ${{{p['a']:g} + p.r}}) (size {p['w']:g} {p['h']:g}) "
            f"{p['drill']}(layers {p['layers']}) {p['rr']}${{p.{param}}})"), param

def write(name, header, module, ps, silk, prefix='P', extra_params=''):
    lines, params = [], []
    for p in ps:
        s, param = pad_js(p, prefix)
        lines.append(s)
        if param not in params: params.append(param)
    pj = ', '.join(f"{k}: {{type: 'net', value: ''}}" for k in params)
    js = f"""{header}
// Generated by tools/gen_ctrl_footprints.py: edit that, not this file.
module.exports = {{
  params: {{ designator: 'IC', value: '', {extra_params}{pj} }},
  body: p => `
  (module {module} (layer F.Cu) (tedit 6500000)
    ${{p.at}}
    (attr smd)
    (fp_text reference "${{p.ref}}" (at 0 0 ${{p.r}}) (layer F.SilkS) ${{p.ref_hide}} (effects (font (size 0.8 0.8) (thickness 0.12))))
    (fp_text value "${{p.value}}" (at 0 0 ${{p.r}}) (layer F.Fab) (effects (font (size 0.8 0.8) (thickness 0.12))))
{silk}
{chr(10).join(lines)}
  )`
}}
"""
    open(os.path.join(OUT, name), 'w').write(js)
    print('wrote', name, len(ps), 'pads')

def rect(x0, y0, x1, y1, layer='F.SilkS', w=0.12):
    return '\n'.join(f'    (fp_line (start {a:g} {b:g}) (end {c:g} {d:g}) (layer {layer}) (width {w}))'
                     for a, b, c, d in ((x0, y0, x1, y0), (x1, y0, x1, y1), (x1, y1, x0, y1), (x0, y1, x0, y0)))

write('mdbt50q.js',
      '// Raytac MDBT50Q-1MV2 (nRF52840, chip antenna), LCSC C5118826, 10.5 x 15.5 x 2.05 mm. The antenna end is at -y\n'
      '// (local), which goes at the board edge; tools/add_keepouts.py adds the antenna copper keep-out.',
      'Raytac_MDBT50Q', pads(f'{LIB}/RF_Module.pretty/Raytac_MDBT50Q.kicad_mod'),
      rect(-5.25, -7.75, 5.25, 7.75) + '\n' + rect(-5.25, -7.75, 5.25, -4, 'F.Fab', 0.1) +
      '\n    (fp_text user "ANTENNA" (at 0 -5.9 ${p.r}) (layer F.Fab) (effects (font (size 0.8 0.8) (thickness 0.12))))'
      '\n    (fp_circle (center -5.9 7.2) (end -5.65 7.2) (layer F.SilkS) (width 0.25))')
usb = pads(NRFMICRO_USB)
for p in usb:   # the signal pads run right up to the notch; pull their back ends in 0.15 mm so they stay clear of it,
    # and narrow the 0.3 mm ones to 0.28 mm so the 0.5 mm pitch leaves a 0.22 mm gap (the board's rule is 0.2 mm)
    if p['kind'] == 'smd' and abs(p['y'] - 0.4) < 1e-6 and abs(p['h'] - 0.8) < 1e-6:
        p['y'], p['h'] = 0.475, 0.65
        if abs(p['w'] - 0.3) < 1e-6: p['w'] = 0.28
write('usbc_mid.js',
      '// 16-pin mid-mount USB-C receptacle, LCSC C168688 (918-418K2024S40000), from joric/nrfmicro (public domain).\n'
      '// The board needs a 9.14 x 5.5 mm notch at -y (local), open to the board edge; it sits 1.58 mm above and below\n'
      '// the PCB surface. Pads: A1 GND, A4 VBUS, A5 CC1, B5 CC2, A6/B6 D+, A7/B7 D-, S1 shield.',
      'USB_C_C168688', usb, rect(-4.57, -5.5, 4.57, 1.2, 'F.Fab', 0.1), prefix='')
write('sot23.js', '// SOT-23-5 / SOT-23-6 (KiCad library land pattern); pins 1-3 down the left side, counter-clockwise.\n'
      '// For SOT-23-5 leave P6 empty: pad 6 is dropped.', 'SOT-23', pads(f'{LIB}/Package_TO_SOT_SMD.pretty/SOT-23-6.kicad_mod'),
      rect(-0.8, -1.5, 0.8, 1.5, 'F.Fab', 0.1) + '\n    (fp_circle (center -1.9 -1.6) (end -1.75 -1.6) (layer F.SilkS) (width 0.25))')
write('xtal_3215.js', '// 32.768 kHz crystal, 3.2 x 1.5 mm (e.g. Epson Q13FC13500004, LCSC C32346).', 'Crystal_3215',
      pads(f'{LIB}/Crystal.pretty/Crystal_SMD_3215-2Pin_3.2x1.5mm.kicad_mod'), rect(-1.6, -0.75, 1.6, 0.75, 'F.Fab', 0.1))
# SOT-23-5: pin 5 is where SOT-23-6 has pin 6 (top right); pad 5 of the 6-pin (right middle) is absent.
t = open(os.path.join(OUT, 'sot23.js')).read()
t = t.replace("params: { designator: 'IC', value: '', ", "params: { designator: 'IC', value: '', pins: 6, ")
t = re.sub(r'(    \(pad 5 [^\n]*\n)', r'${p.pins == 6 ? `\1` : ""}', t)
t = re.sub(r'\(pad 6 ([^\n]*)\$\{p\.P6\}\)', r'(pad ${p.pins == 6 ? 6 : 5} \1${p.pins == 6 ? p.P6 : p.P5})', t)
t = t.replace('${p.pins == 6 ? `    (pad 5', '${p.pins == 6 ? `    (pad 5').replace('${p.P5})\n`', '${p.P5})\n`')
open(os.path.join(OUT, 'sot23.js'), 'w').write(t)
