#!/usr/bin/env python3
"""Derive ergogen-3row/config.yaml (3 x 6 + 3 per half, columns angled inward) from ergogen/config.yaml.

Changes: no number row; each half's key block rotated ANGLE degrees so the column tops lean toward
the centre; rows renumbered (top R0, home R1, bottom R2, thumbs R3); the mono matrix becomes
6 rows x 7 columns (left rows 0-2, right rows 3-5, thumbs in column 6). Centre-area parts
(controller, display, LEDs, battery, charge link, reset) stay where they are on the 4-row boards.
usage: python3 tools/make_3row.py [angle] [shift_x] [shift_y]
"""
import re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ANGLE = float(sys.argv[1]) if len(sys.argv) > 1 else 10
SX = float(sys.argv[2]) if len(sys.argv) > 2 else -3
SY = float(sys.argv[3]) if len(sys.argv) > 3 else 17
s = open(os.path.join(ROOT, 'ergogen/config.yaml')).read()

s = s.replace('# Yoga Book 9i Gen 9 low-profile split keyboard',
              f'# Yoga Book 9i Gen 9 low-profile split keyboard, 3-ROW variant (generated by tools/make_3row.py:\n'
              f'# edit ergogen/config.yaml or the script, not this file). Key blocks rotated {ANGLE:g} deg inward.')
s = s.replace('  name: yoga-split\n', '  name: yoga-split-3row\n')

# --- drop the number row
s = re.sub(r'\n            num: \{[^\n]*\}', '', s)
s = s.replace('        num: {row_net: R0, row_i: 0}\n', '')

# --- renumber rows (top 0, home 1, bottom 2, thumbs 3)
s = s.replace('bottom: {row_net: R3, row_i: 3}', 'bottom: {row_net: R2, row_i: 2}')
s = s.replace('home: {row_net: R2, row_i: 2}', 'home: {row_net: R1, row_i: 1}')
s = s.replace('top: {row_net: R1, row_i: 1}', 'top: {row_net: R0, row_i: 0}')
s = s.replace('one: {row_net: R4, row_i: 4}', 'one: {row_net: R3, row_i: 3}')

# --- mono matrix: 6 x 7. matrix key (row r, col c): left MR r / MC c, right MR r+3 / MC c
ROWI = {'top': 0, 'home': 1, 'bottom': 2}
COLI = {'outer': 0, 'pinky': 1, 'ring': 2, 'middle': 3, 'index': 4, 'inner': 5}
def mono_key(m):
    col, row = m.group('col'), m.group('row')
    r, c = ROWI[row], COLI[col]
    return f'{row}: {{mono_row: MR{r}, mono_col: MC{c}, mirror: {{mono_row: MR{r + 3}, mono_col: MC{c}}}}}'
out, col = [], None
for line in s.split('\n'):
    m = re.match(r'        (outer|pinky|ring|middle|index|inner):$', line)
    if m: col = m.group(1)
    m = re.match(r'(\s+)(top|home|bottom): \{mono_row: [^\n]*\}\}$', line)
    if m and col:
        r, c = ROWI[m.group(2)], COLI[col]
        line = f'{m.group(1)}{m.group(2)}: {{mono_row: MR{r}, mono_col: MC{c}, mirror: {{mono_row: MR{r + 3}, mono_col: MC{c}}}}}'
    out.append(line)
s = '\n'.join(out)
for k, t in enumerate(['tucky', 'home', 'reachy']):
    s = re.sub(rf'(        {t}:\n          key: \{{)mono_row: MR\d, mono_col: MC\d, mirror: \{{mono_row: MR\d, mono_col: MC\d\}}',
               rf'\1mono_row: MR{k}, mono_col: MC6, mirror: {{mono_row: MR{k + 3}, mono_col: MC6}}', s)

# --- rotate the key block: matrix zone anchored at (SX, SY), rotated -ANGLE (clockwise on the left)
s = s.replace('    matrix:\n      columns:', f'    matrix:\n      anchor: {{shift: [{SX}, {SY}], rotate: {-ANGLE}}}\n      columns:')

# --- mirror axis stays at x = cx: matrix_inner_bottom (local (90, 3)) moves with the rotation
import math
a = math.radians(ANGLE)
inner_x = SX + 90 * math.cos(a) + 3 * math.sin(a)
s = s.replace('    distance: 82   # puts the mirror axis at x = cx', f'    distance: {2 * (131 - inner_x):.3f}   # puts the mirror axis at x = cx')

# --- controller pins: rows R0-R3 only; mono MR0-5 x MC0-6
s = s.replace('          P8: R4\n', '')
s = re.sub(r'          P10: MC7\n', '', s)
s = re.sub(r'          P0: MC8\n', '', s)
# --- innermost thumb key is a vertical 1.5u, like the Corne's: switch moved 4.25 mm up (along the
# key's own axis) so the cap grows toward the key block; caps/keycaps outlines get a 1.5u entry for it
TALL = 17 * 0.5 / 2   # half of the extra 0.5u at 17 mm row pitch
s = s.replace('splay: -10, origin: [-9, -8.5], column_net: C5, col_i: 5}',
              f'splay: -10, origin: [-9, -8.5], shift: [0, {TALL}], height: 25, column_net: C5, col_i: 5}}')
assert f'shift: [0, {TALL}]' in s
NOT_TALL = '/^(?!(mirror_)?thumb_reachy)/'
TALL_ONLY = '/^(mirror_)?thumb_reachy/'
for name, w, h in (('keycaps', 17.5, 16.5), ('caps', 18.5, 17.5)):
    i = s.index(f'  {name}:', s.index('outlines:'))
    j = s.index('\n  ', s.index('size:', i)) if False else s.index('\n', s.index('size:', i))
    block = s[i:j]
    new = block.replace('where: true', f'where: {NOT_TALL}') + \
        f'\n    - what: rectangle\n      where: {TALL_ONLY}\n      size: [{w}, {h + 8.5}]'
    s = s[:i] + new + s[j:]

# the tall key's switch turns 90 deg: a Choc v1 stem only takes a cap one way round, so a 1.5u cap
# standing vertical needs the switch rotated under it (as on the Corne Chocolate)
def tall_choc(where_all, where_main, talls, net):
    global s
    old = (f'      choc:\n        what: choc\n        where: {where_all}\n'
           f'        params: {{hotswap: false, keycaps: true, from: "{{{{colrow}}}}", to: "{{{{{net}}}}}"}}\n')
    assert old in s, where_all
    new = old.replace(f'where: {where_all}', f'where: {where_main}')
    for i, (where_tall, rot) in enumerate(talls):
        new += (f'      choc_tall{i or ""}:\n        what: choc\n        where: {where_tall}\n        adjust: {{rotate: {rot}}}\n'
                f'        params: {{hotswap: false, keycaps: false, from: "{{{{colrow}}}}", to: "{{{{{net}}}}}"}}\n')
    s = s.replace(old, new, 1)
# ergogen mirrors the adjust rotation on the right half; -90 there keeps the switch's pins on the
# same side of its diode as on the left (+90 would land a switch pin on the diode's pad)
L, R = ('/^thumb_reachy/', 90), ('/^mirror_thumb_reachy/', -90)
tall_choc('/^(matrix|thumb)_/', '/^(matrix|thumb)_(?!reachy)/', [L], 'column_net')
tall_choc('/^mirror_/', '/^mirror_(?!thumb_reachy)/', [R], 'column_net')
tall_choc('/^(matrix|thumb|mirror)_/', '/^(?!(mirror_)?thumb_reachy)(matrix|thumb|mirror)_/', [L, R], 'mono_col')

open(os.path.join(ROOT, 'ergogen-3row/config.yaml'), 'w').write(s)
print('wrote ergogen-3row/config.yaml')
