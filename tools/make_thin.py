#!/usr/bin/env python3
"""Generate ergogen-thin/config.yaml: the thin build with Kailh PG1316S scissor-style switches.

Starts from ergogen-3row/config.yaml (run tools/make_3row.py first) and changes:
* switches: PG1316S (SMD, reflowed by JLC) on every key, inner thumb back to 1u (no 1.5u caps exist
  for the PG1316S), 16 x 16.25 mm caps;
* diodes: SOD-123 on the TOP side, in the gap between columns, so the bottom of the PCB is flat and
  sits on the case floor;
* everything else SMD on the top side too: side slide switch, 1206 fuse and resistor, SOD-123FL TVS,
  0805 status LEDs and resistors (no nice!view: it's too tall), reset pads;
* battery: a 4 x 30 x 40 mm cell (403040) in a notch in the PCB's front corner, on a thinned floor;
* PCB ordered at 0.8 mm.
usage: python3 tools/make_thin.py
"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(ROOT, 'ergogen-3row/config.yaml')).read()
s = s.replace('3-ROW variant (generated by tools/make_3row.py:',
              'THIN variant with PG1316S switches (generated by tools/make_thin.py from the 3-row config,\n# which is generated by tools/make_3row.py:')
s = s.replace('  name: yoga-split-3row\n', '  name: yoga-split-thin\n')

# --- inner thumb back to 1u, PG1316S cap sizes
s = re.sub(r', shift: \[0, [\d.]+\], height: [\d.]+', '', s)
for name, size in (('keycaps', '[16.05, 16.25]'), ('caps', '[17.05, 17.25]')):
    m = re.search(rf'(\n  {name}:[^\n]*\n)    - what: rectangle\n      where: [^\n]*\n      size: [^\n]*\n    - what: rectangle\n      where: [^\n]*\n      size: [^\n]*', s)
    assert m, name
    s = s[:m.start()] + m.group(1) + f'    - what: rectangle\n      where: true\n      size: {size}' + s[m.end():]
s = s.replace('# 17.5 x 16.5 Choc keycap footprints', '# 16.05 x 16.25 PG1316S keycaps')

# --- battery notches in the front corners (x -4.5 .. 36.5, open to the front edge), both sides
CELL = '''    - what: rectangle
      operation: subtract
      size: [41, 40]
      adjust.shift: [{x}, -23]
'''
m = re.search(r'(  pcb_mono:\n    - what: rectangle\n      size: [^\n]*\n      corner: [^\n]*\n      adjust.shift: [^\n]*\n)', s)
assert m
s = s[:m.end()] + CELL.format(x=16) + CELL.format(x=246) + s[m.end():]

# --- footprint blocks, section by section
def blocks(sec):
    """split a pcbs section's footprints into (name, text) blocks, comments kept with the next block"""
    head, body = sec.split('    footprints:\n', 1)
    out, cur, name, pending = [], [], None, []
    for line in body.split('\n'):
        m = re.match(r'      ([a-z0-9_]+):', line)
        if line.startswith('      #'):
            pending.append(line); continue
        if m:
            if name: out.append((name, '\n'.join(cur)))
            name, cur = m.group(1), pending + [line]; pending = []
        else:
            cur.append(line)
    if name: out.append((name, '\n'.join(cur)))
    return head, out

def fp(name, what, x=None, y=None, rot=0, params=None, where=None, adjust=None):
    t = f'      {name}:\n        what: {what}\n'
    if where: t += f'        where: {where}\n'
    if adjust: t += f'        adjust: {adjust}\n'
    elif x is not None: t += f'        adjust: {{shift: [{x:g}, {y:g}], rotate: {rot}}}\n'
    if params: t += f'        params: {params}\n'
    return t.rstrip('\n')

def centre(side, keys_where, col_net, row_net):
    """centre-area parts for one board; side = 'left' | 'right' | 'mono'"""
    X = (lambda x: x) if side != 'right' else (lambda x: 262 - x)
    m = 131 - 113 if side == 'mono' else 0          # the mono's controller sits on the centre line
    Y = lambda x: X(x) + m
    t = [fp('switch', 'pg1316s', where=keys_where, params=f'{{from: "{{{{colrow}}}}", to: "{{{{{col_net}}}}}", keycaps: true}}'),
         fp('diode', 'diode_sod123', where=keys_where, adjust='{shift: [9, 0], rotate: 90}',
            params=f'{{side: F, from: "{{{{colrow}}}}", to: "{{{{{row_net}}}}}"}}')]
    t.append(fp('power', 'power_switch', X(93) + m, 68, 0, '{from: BAT_P, to: RAW}'))
    # the cell (403040, 4 x 30 x 40 mm) sits in a notch in the PCB in the front corner, on a thinned
    # floor, so it's 4 mm thick without making the case thicker; its leads go to these pads
    t.append(fp('battery', 'battery_pads', 39.5 if side != 'right' else 262 - 39.5, -8, 90, '{pos: BAT_P, neg: GND}'))
    t.append(fp('reset', 'tht2', Y(118.3), 33, 0,
                '{designator: SW, from: RST, to: GND, pitch: 2.54, value: "reset pads (short with tweezers)", label: RST}'))
    if side != 'mono':
        r = 0 if side == 'left' else 180
        kind = 'male' if side == 'left' else 'female'
        ab = 'a: LINK_B, b: GND' if side == 'left' else 'a: GND, b: LINK_B'
        t.append(fp('chg_link', 'charge_link', X(125.5), 28, r, f'{{{ab}, kind: {kind}}}'))
        t.append(fp('chg_fuse', 'smd_1206', X(121.5), 22, 90, '{designator: F, side: F, from: BAT_P, to: LINK_F, value: "PTC 0.1A hold 1206"}'))
        t.append(fp('chg_res', 'smd_1206', X(121.5), 16.5, 90, '{designator: R, side: F, from: LINK_F, to: LINK_B, value: "10R 1206 0.25W"}'))
        t.append('      # ESD clamp on the exposed charge-link contact (SMF10A, SOD-123FL, 10 V standoff)')
        t.append(fp('chg_tvs', 'diode_sod123', X(124.2), 20, 90, '{designator: D, side: F, from: GND, to: LINK_B}'))
    t.append('      # status LEDs (0805, red/green/blue) on the display pins, driven by zmk-rgbled-widget')
    for y, c, net, pin, val in ((3, 'r', 'LED_R', 'CS', '680R'), (6.5, 'g', 'LED_G', 'MOSI', '150R'), (10, 'b', 'LED_B', 'SCK', '150R')):
        t.append(fp(f'led_{c}', 'smd_0805', Y(119.5), y, 0, f'{{designator: LED, led: true, from: {net}, to: GND, value: "{ {"r": "red", "g": "green", "b": "blue"}[c]} LED 0805"}}'))
        t.append(fp(f'led_{c}_res', 'smd_0805', Y(123.2), y, 0, f'{{designator: R, from: {pin}, to: {net}, value: "{val} 0805"}}'))
    return t

KEEP = ('mcu',)
def rebuild(sec, side, keys_where, col_net, row_net):
    head, bl = blocks(sec)
    kept = [b for n, b in bl if n in KEEP or re.match(r'h\d+$', n)]
    return head + '    footprints:\n' + '\n'.join(centre(side, keys_where, col_net, row_net) + kept) + '\n'

i = s.index('pcbs:\n')
pcbs = s[i:]
parts = re.split(r'(?m)^  (left|right|mono):\n', pcbs)
out = parts[0]
for k in range(1, len(parts), 2):
    side, sec = parts[k], parts[k + 1]
    where = {'left': '/^(matrix|thumb)_/', 'right': '/^mirror_/', 'mono': '/^(matrix|thumb|mirror)_/'}[side]
    col = 'mono_col' if side == 'mono' else 'column_net'
    row = 'mono_row' if side == 'mono' else 'row_net'
    out += f'  {side}:\n' + rebuild(sec, side, where, col, row)
s = s[:i] + out
os.makedirs(os.path.join(ROOT, 'ergogen-thin'), exist_ok=True)
open(os.path.join(ROOT, 'ergogen-thin/config.yaml'), 'w').write(s)
fpdir = os.path.join(ROOT, 'ergogen-thin/footprints')
if not os.path.lexists(fpdir): os.symlink('../ergogen/footprints', fpdir)
print('wrote ergogen-thin/config.yaml')
