#!/usr/bin/env python3
"""Port blaise's Cannonkeys Link keymap (BlaiseRideout/zmk-configs, link/link.keymap) to this board.

The Link has a number row, the corne 3x6+3 block, an encoder push button per half (row 3, middle)
and two extra outer thumb keys per half: 60 positions. This board is the same minus the two encoder
buttons and the four outer thumb keys: 54 positions, in the same order. Everything else in the
file (behaviors, defines, layers) is kept as is.

usage: python3 tools/port_link_keymap.py path/to/zmk-configs/link/link.keymap
writes config/yoga_split.keymap and config/yoga_mono.keymap (user-config keymaps, which ZMK
uses in place of the shields' default keymaps).
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(sys.argv[1]).read()

# Link position -> dropped. Rows: 0-11 num, 12-23 top, 24-35 home, 36-49 bottom (+2 encoders),
# 50-59 thumbs (outer 2, inner 3 | inner 3, outer 2).
DROP = {42, 43, 50, 51, 58, 59}

def split_bindings(body):
    toks = [t.strip() for t in re.split(r'(?=&)', body) if t.strip()]
    assert all(t.startswith('&') for t in toks), toks
    return toks

def fmt(toks):
    assert len(toks) == 54, len(toks)
    rows = [toks[i:i + 12] for i in range(0, 48, 12)] + [toks[48:]]
    width = max(len(t) for t in toks)
    out = []
    for r in rows[:4]:
        out.append('    ' + ' '.join(t.ljust(width) for t in r[:6]) + '    ' + ' '.join(t.ljust(width) for t in r[6:]))
    pad = ' ' * (4 + 3 * (width + 1))
    out.append(pad + ' '.join(t.ljust(width) for t in rows[4][:3]) + '    ' + ' '.join(t.ljust(width) for t in rows[4][3:]))
    return '\n'.join(l.rstrip() for l in out)

def port(m):
    toks = split_bindings(m.group(2))
    assert len(toks) == 60, len(toks)
    kept = [t for i, t in enumerate(toks) if i not in DROP]
    return f'{m.group(1)}\n{fmt(kept)}\n{m.group(3)}'

keymap_start = src.index('keymap {')
head, body = src[:keymap_start], src[keymap_start:]
body = re.sub(r'\n\s*sensor-bindings = <[^>]*>;\n', '\n', body)  # no encoders on this board
body, n = re.subn(r'(\bbindings = <)(.*?)(\s*>;)', port, body, flags=re.S)
head = head.replace(
    '  // Layout: the corne 3x6+3 layout sits on rows 1-3 and the three inner thumb\n'
    '  // keys of each half. The Link adds a number row, an encoder push button on\n'
    '  // each half (row 3, middle) and two outer thumb keys per half.\n',
    '  // Layout: number row, the corne 3x6 block and three thumb keys per half\n'
    '  // (the Link\'s inner thumbs; its encoder buttons and outer thumbs are dropped).\n')
banner = ('/*\n * Yoga Split / Yoga Mono keymap, generated by tools/port_link_keymap.py from\n'
          ' * BlaiseRideout/zmk-configs link/link.keymap. Edit that file and re-run the script, or\n'
          ' * edit this one directly if the two boards should diverge.\n */\n\n')
text = banner + head + body
for name in ('yoga_split', 'yoga_mono'):
    with open(os.path.join(ROOT, 'config', f'{name}.keymap'), 'w') as f:
        f.write(text)
print(f'ported {n} layers')
